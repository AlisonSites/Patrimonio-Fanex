  ('9° ANO A'), ('9° ANO B'),
  ('1ª SÉRIE'), ('2ª SÉRIE'), ('3ª SÉRIE')
) as t(nome)
where not exists (
  select 1 from public.turmas x where x.nome = t.nome and x.ano_letivo = 2026
);

